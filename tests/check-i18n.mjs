/**
 * Проверка русского рантайма i18n (форк: русский интерфейс панели).
 *
 * Зачем отдельный тест, а не «словарь и так видно»: правило `T()` — это не
 * поиск по ключу, а regexp-матчинг шаблонов (`已校验 {0} 个账号：{1}。`).
 * Такое нельзя проверить чтением словаря — ошибка в порядке правил видна
 * только на **готовой** строке.
 *
 * Конкретные регрессии, которые здесь зафиксированы:
 *   1) правила сортировались по длине regexp-источника, а `([\s\S]+?)` — это
 *      11 символов, поэтому общее правило с одним `{0}` оказывалось «длиннее»
 *      конкретного с двумя и навсегда его затеняло;
 *   2) значение, подставленное в шаблон, **само является界面-строкой**
 *      (`2 个正常`), и без рекурсивного перевода оставалось китайским.
 *
 * Импорт идёт в исходник `.ts` — Node 24 стрипает типы без флагов. Так тест
 * проверяет то же, что попадёт в бандл, а не отдельную копию словаря.
 */
import { translate } from '../src/i18n/runtime.ts'

const cases = [
  // [язык, вход, ожидание]
  ['ru', '校验中…', 'Проверка…'],
  // конкретное правило (2 дырки) обязано победить общее (1 дырка)
  ['ru', '已校验 2 个账号：全部正常。', 'Проверено аккаунтов: 2 — все в порядке.'],
  // …и подставленное значение переводится рекурсивно
  ['ru', '已校验 3 个账号：2 个正常。', 'Проверено аккаунтов: 3 — 2 в порядке.'],
  // подстановка внутри шаблона не должна съедать соседний текст
  ['ru', '重登完成 1/3', 'Перелогин завершён 1/3'],
  ['ru', '账号级限制已解除（16:20）。', 'Ограничение аккаунта снято (16:20).'],
  // ключ с настоящим переводом строки
  ['ru', 'путь\n配置文件：C:\\x', 'путь\nФайл настроек: C:\\x'],
  // 🔴 Число в подстановке не должно исчезать. Регрессия: перевод `'{0} 万'`
  // компилировался в `$1` + следующая цифра `0` ⇒ `$10` ⇒ ссылка на десятую
  // группу, которой нет ⇒ `String.replace` вставлял пустую строку, и в
  // «Статистике токенов» оставалось « тыс.» вместо числа.
  ['ru', '142.5 万', '142.50 тыс.'],
  ['ru', '1.23 亿', '1.2300 млн'],
  // …и соседнее правило `{0} 万字符` не должно быть задето этой правкой
  ['ru', '40 万字符', '400 тыс. символов'],
  // непереведённое возвращается как есть, а не пустой строкой
  ['ru', 'нет такого ключа', 'нет такого ключа'],
  // zh — тождественная функция
  ['zh', '校验中…', '校验中…'],
]

let failed = 0
for (const [lang, input, want] of cases) {
  const got = translate(lang, input)
  const ok = got === want
  if (!ok) {
    failed++
    console.log(`  ✗ [${lang}] ${JSON.stringify(input)}\n      получено: ${JSON.stringify(got)}\n      ожидалось: ${JSON.stringify(want)}`)
  } else {
    console.log(`  ✓ [${lang}] ${JSON.stringify(input)} → ${JSON.stringify(got)}`)
  }
}

console.log(`\n[i18n] ${cases.length - failed}/${cases.length}通过`)
process.exitCode = failed ? 1 : 0
