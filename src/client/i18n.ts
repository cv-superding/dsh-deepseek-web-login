const catalogs: Record<LocaleId, Record<string, string>> = {
  zh: {}, // identity — Chinese source strings are the keys
  ru,
  en,
}

let current: LocaleId = 'en'
const listeners = new Set<() => void>()

function detectInitial(): LocaleId {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored === 'zh' || stored === 'ru' || stored === 'en') return stored
  } catch {
    /* ignore */
  }
  // Default UI language is English unless the user has chosen otherwise.
  return 'en'
}

current = detectInitial()

/** Translate a Chinese source string. Falls back to the source itself. */
export function t(zh: string): string {
  if (current === 'zh') return zh
  const catalog = catalogs[current]
  return catalog[zh] ?? zh
}

/** Translate with simple `{0}` / `{1}` placeholders. */
export function tf(zh: string, ...args: Array<string | number>): string {
  let out = t(zh)
  args.forEach((a, i) => {
    out = out.replace(new RegExp(`\\{${i}\\}`, 'g'), String(a))
  })
  return out
}

export function getLocale(): LocaleId {
  return current
}

export function setLocale(id: LocaleId): void {
  if (id === current) return
  current = id
  try {
    localStorage.setItem(STORAGE_KEY, id)
  } catch {
    /* ignore */
  }
  for (const fn of listeners) {
    try {
      fn()
    } catch {
      /* ignore */
    }
  }
}

/** Subscribe to locale changes (e.g. to rebuild the panel). Returns unsubscribe. */
export function onLocaleChange(fn: () => void): () => void {
  listeners.add(fn)
  return () => {
    listeners.delete(fn)
  }
}

