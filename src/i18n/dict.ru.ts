import type { Dict } from './runtime.ts'
import { RU_PANEL } from './ru/panel.ts'
import { RU_GATE } from './ru/gate.ts'
import { RU_HOST } from './ru/host.ts'
import { RU_MISC } from './ru/misc.ts'
import { RU_REST } from './ru/rest.ts'

/**
 * Русский словарь целиком.
 *
 * Ключ — **китайская строка-оригинал** из исходников; значение — перевод.
 * Чего нет в словаре, то остаётся китайским: `T()` возвращает входную строку,
 * поэтому неполный словарь никогда не ломает интерфейс, только оставляет
 * непереведённые места. Именно поэтому словарь разбит по файлам и наполняется
 * постепенно, а не «сначала все ключи, потом переводы».
 *
 * Порядок слияния — от важного к второстепенному: каркас панели и аккаунты,
 * затем «Защита от бана», затем тексты host-ошибок, затем остальное. При
 * совпадении ключа побеждает **первый** файл, поэтому дубликат в `rest.ts`
 * не может незаметно перебить выверенный перевод из `panel.ts`.
 */
export const RU: Dict = {
  ...RU_PANEL,
  ...RU_GATE,
  ...RU_HOST,
  ...RU_MISC,
  ...RU_REST,
}